"""Replace raw state-array accesses in src/client with the names src/engine
gives those addresses.

Every name becomes a macro in src/client/client_names.h that expands to
exactly the expression it replaces, so the compiled code cannot change:
    dword_140404A6C[N]                -> name          (an int-sized global)
    *(float *)&dword_140404A6C[N]     -> name          (a float global)
Accesses through another type (a cast to a wider or different type) are
left alone, as is any name that the client already uses for something else.
"""
import re
import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent))
import engine_names

PROJECT = Path(__file__).resolve().parent.parent.parent
CLIENT = PROJECT / 'src/client'
BASE = 0x140404A6C
INTS = {'int32_t', 'uint32_t', 'int', 'unsigned', 'unsigned int'}


def main():
    sources = {p: p.read_bytes().decode('utf-8') for p in sorted(CLIENT.glob('*.[ch]')) if p.name != 'client_names.h'}
    everything = ''.join(sources.values())
    used = set(re.findall(r'\b[A-Za-z_]\w*\b', everything))
    floats, ints = {}, {}
    for name, (ctype, address, header) in engine_names.scalars().items():
        if address < BASE or (address - BASE) % 4 or name in used:
            continue
        index = (address - BASE) // 4
        table = floats if ctype == 'float' else ints if ctype in INTS else None
        if table is None:
            continue
        if index in table:
            sys.exit('%#x has two names in src/engine: %s and %s' % (address, table[index][0], name))
        table[index] = (name, header)
    applied = {}
    existing = CLIENT / 'client_names.h'
    if existing.exists():   # names applied by an earlier run stay
        for m in re.finditer(r'^#define (\w+)[ \t]+([^\n]+?)[ \t]+/\* (\S+) \*/$', existing.read_text(encoding='utf-8'),
                             re.M):
            applied[m.group(1)] = (m.group(2), m.group(3))

    def float_access(m):
        index = int(m.group(1))
        if index not in floats:
            return m.group(0)
        applied[floats[index][0]] = ('(*(float *)&dword_140404A6C[%d])' % index, floats[index][1])
        return floats[index][0]

    def int_access(m):
        index = int(m.group(2))
        if index not in ints or m.group(1):
            return m.group(0)
        applied[ints[index][0]] = ('dword_140404A6C[%d]' % index, ints[index][1])
        return ints[index][0]

    for path, text in sources.items():
        new = re.sub(r'\*\(float \*\)&dword_140404A6C\[(\d+)\]', float_access, text)
        # Not after a cast-and-address-of, where the access is of another type.
        new = re.sub(r'(\*\([^()]*\*\)&)?\bdword_140404A6C\[(\d+)\]', int_access, new)
        if new != text:
            path.write_bytes(new.encode('utf-8'))
    lines = ['/* Names for globals of the shared state array, taken from src/engine, where',
             ' * each is documented. Each expands to the access it replaced in the client',
             ' * code (generated by tools/cleanup/name_client_globals.py). */',
             '#ifndef SR_CLIENT_NAMES_H', '#define SR_CLIENT_NAMES_H', '']
    for name, (expansion, header) in sorted(applied.items(), key=lambda kv: kv[0]):
        lines.append('#define %-36s %-40s /* %s */' % (name, expansion, header))
    lines += ['', '#endif', '']
    (CLIENT / 'client_names.h').write_text('\n'.join(lines), encoding='utf-8', newline='\n')
    print('%d names applied' % len(applied))


if __name__ == '__main__':
    main()
